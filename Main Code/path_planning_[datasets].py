class MultiAgentMonitoring(gym.Env):
    def __init__(self, map_size=(50, 41), num_agents=2, movement_cost_factor=0.01,
                 sensor_stds=0.05, reward_weights=None, max_episode_steps=1000,
                 map_data_path=None, reward_scale_factor=1.0,
                 collision_threshold=0.05, collision_penalty=-5.0, # Collision parameters
                 reward_visited_cells=1.0, reward_peak_discovery=5.0,
                 penalty_time=0.00001, penalty_revisit=0.0):
        super(MultiAgentMonitoring, self).__init__()

        self.map_size = map_size # (rows, columns)
        self.num_agents = num_agents
        self.movement_cost_factor = movement_cost_factor
        self.sensor_stds = sensor_stds
        self.max_episode_steps = max_episode_steps
        self.reward_scale_factor = reward_scale_factor

        # Collision parameters
        self.collision_threshold = collision_threshold
        self.collision_penalty = collision_penalty

        self.gt_map = self._load_map_from_csv(map_data_path)
        # Validate loaded map shape against specified map_size (rows, columns)
        if self.gt_map.shape != self.map_size:
            raise ValueError(f"Loaded map shape {self.gt_map.shape} does not match specified map_size {self.map_size}. Please check map_configs in run_training_and_evaluation.")

        self.gt_map_min = np.min(self.gt_map)
        self.gt_map_max = np.max(self.gt_map)
        self.gt_map_normalized = (self.gt_map - self.gt_map_min) / (self.gt_map_max - self.gt_map_min + 1e-6)

        # Track initial visited cells count for reward calculation per step
        self.initial_visited_cells_count = 0
        self.visited_map = np.zeros(self.map_size) # Reset visited map per episode

        # The 'reward_weights' dict argument is now deprecated in favor of individual args
        self.reward_weights = {
            'visited_cells': reward_visited_cells,
            'peak_discovery': reward_peak_discovery,
            'time_penalty': penalty_time,
            'revisit_penalty': penalty_revisit
        }

        # Action space: num_agents * 2 (for x, y delta for each agent)
        self.action_space = spaces.Box(low=-1.0, high=1.0, shape=(self.num_agents, 2), dtype=np.float32)

        # Observation space: num_agents * (x_pos, y_pos, sensed_value)
        self.observation_dim = self.num_agents * 3
        self.observation_space = spaces.Box(low=-np.inf, high=np.inf, shape=(self.observation_dim,), dtype=np.float32)

        self.current_step = 0
        self.fleet_positions = None
        self.np_random = None # Will be set in reset

    def _load_map_from_csv(self, map_data_path):

        if map_data_path is None or not os.path.exists(map_data_path):
            raise ValueError(f"Map data path '{map_data_path}' is invalid or does not exist.")

        map_data = []
        try:
            with open(map_data_path, 'r') as f:
                reader = csv.reader(f)
                for row in reader:
                    # Filter out empty strings that can result from extra commas or malformed rows
                    cleaned_row = [x.strip() for x in row if x.strip()]
                    if not cleaned_row: # Skip empty rows
                        continue
                    map_data.append([float(x) for x in cleaned_row])
            print(f"\n SUCCESS: Loaded {map_data_path} with shape: ({len(map_data)}, {len(map_data[0])}) with ',' delimiter.")
        except (ValueError, IndexError): # IndexError if a row is empty after cleaning, ValueError if float conversion fails
            # If comma-separated fails, try space delimiter
            map_data = [] # Reset map_data
            try:
                with open(map_data_path, 'r') as f:
                    # Manually read line by line and split by space
                    for line in f:
                        # Split by space and filter out empty strings
                        cleaned_row = [x.strip() for x in line.split(' ') if x.strip()]
                        if not cleaned_row: # Skip empty lines
                            continue
                        map_data.append([float(x) for x in cleaned_row])
                print(f"\n SUCCESS: Loaded {map_data_path} with shape: ({len(map_data)}, {len(map_data[0])}) with ' ' delimiter.")
            except Exception as e:
                raise ValueError(f"Failed to load map from {map_data_path}. Tried comma and space delimiters. Error: {e}")

        loaded_map = np.array(map_data, dtype=np.float32)
        return loaded_map

    def _get_obs(self):
        obs = []
        for i in range(self.num_agents):
            x, y = self.fleet_positions[i]
            x_int, y_int = int(round(x)), int(round(y))
            x_int = np.clip(x_int, 0, self.map_size[1] - 1)
            y_int = np.clip(y_int, 0, self.map_size[0] - 1)

            true_value = self.gt_map_normalized[y_int, x_int]
            noisy_value = true_value + self.np_random.normal(0, self.sensor_stds)
            noisy_value = np.clip(noisy_value, 0.0, 1.0)

            # Normalize positions to [0, 1] range
            obs.extend([x / (self.map_size[1] -1), y / (self.map_size[0] -1), noisy_value])

        return np.array(obs, dtype=np.float32)

    def _sense_and_record(self):
        sensed_values_at_step = []
        for i in range(self.num_agents):
            x, y = self.fleet_positions[i]
            x_int, y_int = int(round(x)), int(round(y))
            x_int = np.clip(x_int, 0, self.map_size[1] - 1)
            y_int = np.clip(y_int, 0, self.map_size[0] - 1)

            true_value = self.gt_map_normalized[y_int, x_int]
            noisy_value = true_value + self.np_random.normal(0, self.sensor_stds)
            noisy_value = np.clip(noisy_value, 0.0, 1.0)

            sensed_values_at_step.append((x, y, noisy_value))
            # Only mark as visited if it's not an obstacle (value above threshold)
            if true_value >= self.collision_threshold:
                self.visited_map[y_int, x_int] = 1 # Mark cell as visited

        return sensed_values_at_step

    def _calculate_reward(self, current_sensed_values_info):
        reward = 0.0

        # Reward for visiting NEW cells
        current_visited_cells_count = np.sum(self.visited_map)
        newly_visited_cells = current_visited_cells_count - self.initial_visited_cells_count
        reward += self.reward_weights['visited_cells'] * newly_visited_cells
        self.initial_visited_cells_count = current_visited_cells_count # Update for next step's calculation

        # Reward for discovering high-value peaks at current step
        current_step_sensed_values = [val for _, _, val in current_sensed_values_info]
        if current_step_sensed_values:
            peak_reward = np.max(current_step_sensed_values)
            reward += self.reward_weights['peak_discovery'] * peak_reward

        # Penalty for each time step
        reward -= self.reward_weights['time_penalty']

        return reward * self.reward_scale_factor

    def reset(self, seed=None, options=None):
        super().reset(seed=seed)
        if seed is not None:
            self.np_random, _ = gym.utils.seeding.np_random(seed)
        else:
            self.np_random, _ = gym.utils.seeding.np_random()

        self.fleet_positions = np.zeros((self.num_agents, 2), dtype=np.float32)

        # Initialize agents in valid (non-obstacle) positions
        for i in range(self.num_agents):
            valid_pos_found = False
            attempts = 0
            while not valid_pos_found and attempts < 1000: # Limit attempts
                x = self.np_random.uniform(0, self.map_size[1]) # x-coordinate
                y = self.np_random.uniform(0, self.map_size[0]) # y-coordinate
                x_int, y_int = int(round(x)), int(round(y))

                # Check if the proposed starting position is traversable
                if 0 <= y_int < self.map_size[0] and 0 <= x_int < self.map_size[1]:
                    if self.gt_map_normalized[y_int, x_int] >= self.collision_threshold:
                        self.fleet_positions[i, 0] = x
                        self.fleet_positions[i, 1] = y
                        valid_pos_found = True
                    else:
                        attempts += 1
                else:
                    attempts += 1

            if not valid_pos_found:
                print(f"Warning: Could not find a valid starting position for agent {i}. Placing at (0,0).")
                self.fleet_positions[i, 0] = 0
                self.fleet_positions[i, 1] = 0


        self.current_step = 0
        self.visited_map = np.zeros(self.map_size) # Reset visited map for the new episode
        self.initial_visited_cells_count = 0 # Reset for new episode reward calculation

        initial_sensed_values = self._sense_and_record()
        self.initial_visited_cells_count = np.sum(self.visited_map) # Set initial count after first sensing

        obs = self._get_obs()
        info = {"fleet_positions": self.fleet_positions.copy(), "sensed_values": initial_sensed_values}

        self.terminated = False
        self.truncated = False

        return obs, info

    def step(self, action):
        # Action is expected to be flattened from the agent, reshape it back to (num_agents, 2)
        action = np.array(action).reshape(self.num_agents, 2)

        # Store old positions to revert in case of collision
        old_positions = self.fleet_positions.copy()
        current_reward = 0.0 # Start with base reward calculation

        # Calculate intended new positions
        intended_new_positions = self.fleet_positions + action

        # Process each agent's movement
        new_fleet_positions = old_positions.copy() # Start with old positions
        for i in range(self.num_agents):
            int_x = int(round(intended_new_positions[i, 0]))
            int_y = int(round(intended_new_positions[i, 1]))

            # Check if intended position is within map bounds
            if 0 <= int_x < self.map_size[1] and 0 <= int_y < self.map_size[0]:
                # Check for collision with map obstacles
                if self.gt_map_normalized[int_y, int_x] < self.collision_threshold:
                    # Collision detected: stay at old position and apply penalty
                    new_fleet_positions[i] = old_positions[i]
                    current_reward += self.collision_penalty
                    # print(f"Agent {i} collided with obstacle at ({int_x}, {int_y}). Penalty: {self.collision_penalty}") # For debugging
                else:
                    # No collision, update position
                    new_fleet_positions[i] = intended_new_positions[i]
            else:
                # Out of bounds: clip and apply penalty
                new_fleet_positions[i, 0] = np.clip(intended_new_positions[i, 0], 0, self.map_size[1] - 1)
                new_fleet_positions[i, 1] = np.clip(intended_new_positions[i, 1], 0, self.map_size[0] - 1)
                current_reward += self.collision_penalty # Apply penalty for hitting boundaries
                # print(f"Agent {i} went out of bounds. Penalty: {self.collision_penalty}") # For debugging

        self.fleet_positions = new_fleet_positions # Update actual positions

        # Calculate movement cost based on the attempted action magnitude
        movement_cost = np.sum(np.abs(action)) * self.movement_cost_factor

        # Sense values at new positions and record visited cells
        current_sensed_values_info = self._sense_and_record()

        # Calculate base reward from environment features (visited cells, peak discovery, time penalty)
        reward_from_env = self._calculate_reward(current_sensed_values_info)

        # Apply reward_scale_factor to the sum of all components
        reward = (reward_from_env - movement_cost + current_reward) * self.reward_scale_factor

        self.current_step += 1

        terminated = False
        truncated = self.current_step >= self.max_episode_steps # Episode ends if max steps reached

        obs = self._get_obs()
        info = {"fleet_positions": self.fleet_positions.copy(), "sensed_values": current_sensed_values_info}

        return obs, reward, terminated, truncated, info

