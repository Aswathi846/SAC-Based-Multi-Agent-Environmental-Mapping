        episode_sensed_coords = [] # Sensed coords for current episode
        episode_sensed_values = [] # Sensed values for current episode

        episode_visited_cells = np.zeros(env.env.map_size)

        # Record initial sensed values and mark initial positions as visited
        for x_init, y_init, sensed_val_init in info["sensed_values"]:
            episode_sensed_coords.append((x_init, y_init))
