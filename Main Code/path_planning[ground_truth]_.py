import optuna
def set_seed(seed):
    torch.manual_seed(seed)
    np.random.seed(seed)
    random.seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)
        torch.backends.cudnn.deterministic = True
        torch.backends.cudnn.benchmark = False

def run_training_and_evaluation(args, map_configs):
    timestamp = datetime.now().strftime("%Y-%m-%d_%H-%M-%S")
    log_base_dir_overall = os.path.join("runs_tuning_groundtruth", f"Tune_Overall_{timestamp}")
    os.makedirs(log_base_dir_overall, exist_ok=True)

    best_trials_per_map = {}

    for map_comb_name, map_config in map_configs.items():
        print(f"\n Starting Optuna Hyperparameter Tuning for Map Type: {map_comb_name} ")
        log_map_dir = os.path.join(log_base_dir_overall, map_comb_name)
        os.makedirs(log_map_dir, exist_ok=True)

        def objective(trial):
            trial_args = type('Args', (object,), args.__dict__.copy())
            trial_args.lr = trial.suggest_float('lr', 1e-5, 1e-3, log=True)
            trial_args.batch_size = trial.suggest_categorical('batch_size', [128, 256, 512])
            trial_args.gamma = trial.suggest_float('gamma', 0.95, 0.999)
            trial_args.reward_visited_cells = trial.suggest_float('reward_visited_cells', 0.5, 5.0)
            trial_args.reward_peak_discovery = trial.suggest_float('reward_peak_discovery', 2.0, 20.0)
            trial_args.penalty_time = trial.suggest_float('penalty_time', 1e-5, 1e-2, log=True)
            trial_args.collision_penalty = trial.suggest_float('collision_penalty', -10.0, -1.0)

            current_run_seed = trial_args.seed + trial.number
            set_seed(current_run_seed)
            run_name = f"Trial{trial.number}_{datetime.now().strftime('%H-%M-%S')}"
            run_log_dir = os.path.join(log_map_dir, run_name)

            run_writer = SummaryWriter(log_dir=run_log_dir)


            print(f"\n Running Trial {trial.number} for {map_comb_name} ")
            print(f"\n Hyperparameters: {trial.params}")

            # Create base env and wrap with StateNormalizer
            base_env = MultiAgentMonitoring(
                map_size=map_config["map_size"], num_agents=map_config["num_agents"],
                movement_cost_factor=trial_args.movement_cost_factor, sensor_stds=map_config["sensor_stds"],
                max_episode_steps=trial_args.max_episode_steps, map_class=map_config["map_class"],
                reward_scale_factor=trial_args.reward_scale_factor, collision_threshold=trial_args.collision_threshold,
                collision_penalty=trial_args.collision_penalty, reward_visited_cells=trial_args.reward_visited_cells,
                reward_peak_discovery=trial_args.reward_peak_discovery, penalty_time=trial_args.penalty_time,
                penalty_revisit=trial_args.penalty_revisit
            )
            env = StateNormalizer(base_env)

            observation_dim = env.observation_space.shape[0]
            action_dim = np.prod(env.action_space.shape)

            agent = SACAgent(observation_dim, action_dim, trial_args, run_writer) # Pass run_writer to SACAgent
            total_num_steps = 0
            training_episode_count = 0

            # Main training loop
            while total_num_steps < trial_args.num_steps:
                obs, info = env.reset(seed=current_run_seed + training_episode_count)
                done, truncated = False, False
                episode_reward, episode_steps = 0, 0

                while not done and not truncated:
                    if total_num_steps < trial_args.start_steps:
                        action = env.action_space.sample().flatten()
                        action_reshaped = action.reshape(env.unwrapped.num_agents, 2)
                    else:
                        if total_num_steps == trial_args.start_steps:
                            print("\n Random exploration complete. Freezing state normalizer.")
                            env.set_training_mode(False)
                        action = agent.select_action(obs)
                        action_reshaped = action.reshape(env.unwrapped.num_agents, 2)

                    next_obs, reward, done, truncated, info = env.step(action_reshaped)
                    agent.replay_buffer.push(obs, action, reward, next_obs, done)
                    obs = next_obs
                    episode_reward += reward
                    episode_steps += 1
                    total_num_steps += 1

                    if len(agent.replay_buffer) > trial_args.batch_size and total_num_steps > trial_args.start_steps:
                        agent.update_parameters(agent.replay_buffer, trial_args.batch_size, agent.updates, run_writer)
                        agent.updates += 1

                run_writer.add_scalar('episode/reward', episode_reward, training_episode_count)
                print(f"\n Trial {trial.number}, Episode: {training_episode_count}, Steps: {total_num_steps}, Reward: {episode_reward:.2f}")
                training_episode_count += 1

                # Optuna pruning
                if training_episode_count % trial_args.eval_interval == 0:
                    trial.report(episode_reward, training_episode_count)
                    if trial.should_prune():
                        run_writer.close() # Close writer before pruning
                        raise optuna.exceptions.TrialPruned()

            print("\n Training Complete for Trial ")
            # Pass run_writer and trial.params to evaluate_agent
            eval_metrics = evaluate_agent(env, agent, trial_args.num_eval_episodes, current_run_seed, run_writer, trial.params)
            run_writer.close()
            env.close()
            return eval_metrics["Avg Reward"]


        study = optuna.create_study(direction="maximize", pruner=optuna.pruners.MedianPruner())
        study.optimize(objective, n_trials=args.num_trials)

        print(f"\n Optuna Study Complete for {map_comb_name} ")
        best_trial = study.best_trial
        print(f"\n Best trial value: {best_trial.value:.4f}")
        print("\n Best hyperparameters:")
        for key, value in best_trial.params.items():
            print(f"    {key}: {value}")

        best_trials_per_map[map_comb_name] = best_trial

    # Find and print overall best results
    print("\n" + "="*50)
    print("\n Overall Best Results Across All Map Types ")
    print("="*50)

    overall_best_trial = None
    overall_best_map_name = None

    # Print best results for each map type
    print("\n" + "-"*20)
    print(" Best Results Per Map Type ")
    print("-"*20)
    for map_name, trial in best_trials_per_map.items():
        print(f"\n Map Type: {map_name}")
        print(f"\n Best Trial Value: {trial.value:.4f}")
        print("\n Best Hyperparameters:")
        for key, value in trial.params.items():
            print(f"    {key}: {value}")

        if overall_best_trial is None or trial.value > overall_best_trial.value:
            overall_best_trial = trial
            overall_best_map_name = map_name


