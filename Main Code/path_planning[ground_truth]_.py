class StateNormalizer(gym.Wrapper):
    def __init__(self, env):
        super().__init__(env)
        self.state_sum = np.zeros(self.observation_space.shape, dtype=np.float32)
        self.state_sq_sum = np.zeros(self.observation_space.shape, dtype=np.float32)
        self.state_count = 0
        self.state_mean = np.zeros(self.observation_space.shape, dtype=np.float32)
        self.state_std = np.ones(self.observation_space.shape, dtype=np.float32)
        self.epsilon = 1e-8
        self.is_training = True

    def _update_stats(self, obs):
        if not self.is_training:
            return
        self.state_sum += obs
        self.state_sq_sum += obs ** 2
        self.state_count += 1
        self.state_mean = self.state_sum / self.state_count
        self.state_std = np.sqrt(np.maximum(self.state_sq_sum / self.state_count - self.state_mean ** 2, self.epsilon))

    def reset(self, **kwargs):
        obs, info = self.env.reset(**kwargs)
        self._update_stats(obs)
        normalized_obs = (obs - self.state_mean) / self.state_std
        return normalized_obs, info

    def step(self, action):
        obs, reward, terminated, truncated, info = self.env.step(action)
        self._update_stats(obs)
        normalized_obs = (obs - self.state_mean) / self.state_std
        return normalized_obs, reward, terminated, truncated, info

    def set_training_mode(self, mode):
        self.is_training = mode

class ReplayBuffer:
    def __init__(self, capacity):
        self.buffer = deque(maxlen=capacity)

    def push(self, state, action, reward, next_state, done):
        self.buffer.append((state, action, reward, next_state, done))

    def sample(self, batch_size):
        if len(self.buffer) < batch_size:
            raise ValueError(f"Replay buffer needs at least {batch_size} samples, but has only {len(self.buffer)}.")
        state, action, reward, next_state, done = zip(*random.sample(self.buffer, batch_size))
        return np.array(state, dtype=np.float32), np.array(action, dtype=np.float32), \
               np.array(reward, dtype=np.float32), np.array(next_state, dtype=np.float32), \
               np.array(done, dtype=np.float32)

    def __len__(self):
        return len(self.buffer)

