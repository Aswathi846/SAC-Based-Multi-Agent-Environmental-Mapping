class ValueNetwork(nn.Module):
    def __init__(self, observation_dim, hidden_size):
        super(ValueNetwork, self).__init__()
        self.fc1 = nn.Linear(observation_dim, hidden_size)
        self.fc2 = nn.Linear(hidden_size, hidden_size)
        self.fc3 = nn.Linear(hidden_size, 1)
    def forward(self, state):
        x = F.relu(self.fc1(state))
        x = F.relu(self.fc2(x))
        return self.fc3(x)

class QNetwork(nn.Module):
    def __init__(self, observation_dim, action_dim, hidden_size):
        super(QNetwork, self).__init__()
        # Q1
        self.fc1_q1 = nn.Linear(observation_dim + action_dim, hidden_size)
        self.fc2_q1 = nn.Linear(hidden_size, hidden_size)
        self.fc3_q1 = nn.Linear(hidden_size, 1)
        # Q2
        self.fc1_q2 = nn.Linear(observation_dim + action_dim, hidden_size)
        self.fc2_q2 = nn.Linear(hidden_size, hidden_size)
        self.fc3_q2 = nn.Linear(hidden_size, 1)
    def forward(self, state, action):
        sa = torch.cat([state, action], 1)
        x1 = F.relu(self.fc1_q1(sa))
        x1 = F.relu(self.fc2_q1(x1))
        q1 = self.fc3_q1(x1)
        x2 = F.relu(self.fc1_q2(sa))
        x2 = F.relu(self.fc2_q2(x2))
        q2 = self.fc3_q2(x2)
        return q1, q2

class GaussianPolicy(nn.Module):
    def __init__(self, observation_dim, action_dim, hidden_size):
        super(GaussianPolicy, self).__init__()
        self.fc1 = nn.Linear(observation_dim, hidden_size)
        self.fc2 = nn.Linear(hidden_size, hidden_size)
        self.mean_linear = nn.Linear(hidden_size, action_dim)
        self.log_std_linear = nn.Linear(hidden_size, action_dim)
        self.log_std_min = -20
        self.log_std_max = 2
    def forward(self, state):
        x = F.relu(self.fc1(state))
        x = F.relu(self.fc2(x))
        mean = self.mean_linear(x)
        log_std = self.log_std_linear(x)
        log_std = torch.clamp(log_std, self.log_std_min, self.log_std_max)
        return mean, log_std
    def sample(self, state):
        mean, log_std = self.forward(state)
        std = log_std.exp()
        normal = Normal(mean, std)
        z = normal.rsample() # Use rsample for reparameterization trick
        action = torch.tanh(z)
        log_prob = normal.log_prob(z) - torch.log(1 - action.pow(2) + 1e-6)
        log_prob = log_prob.sum(1, keepdim=True)
        return action, log_prob, mean, log_std

#SAC Agent
class SACAgent:
    def __init__(self, observation_dim, action_dim, args, writer):
        self.gamma = args.gamma
        self.tau = args.tau
        self.lr = args.lr
        self.alpha = torch.tensor(args.alpha, requires_grad=False, device=args.device)
        self.auto_entropy_tuning = args.auto_entropy_tuning
        self.target_entropy = -torch.prod(torch.Tensor([action_dim]).to(args.device)).item()
        self.hidden_size = args.hidden_size
        self.device = args.device
        self.writer = writer

        self.value_net = ValueNetwork(observation_dim, self.hidden_size).to(self.device)
        self.target_value_net = ValueNetwork(observation_dim, self.hidden_size).to(self.device)
        self.q_net1 = QNetwork(observation_dim, action_dim, self.hidden_size).to(self.device)
        self.q_net2 = QNetwork(observation_dim, action_dim, self.hidden_size).to(self.device)
        self.policy_net = GaussianPolicy(observation_dim, action_dim, self.hidden_size).to(self.device)

        # Use a single Q-network class with two instances for soft updates
        self.target_q_net1 = QNetwork(observation_dim, action_dim, self.hidden_size).to(self.device)
        self.target_q_net2 = QNetwork(observation_dim, action_dim, self.hidden_size).to(self.device)

        # Copy weights
        self.target_value_net.load_state_dict(self.value_net.state_dict())
        self.target_q_net1.load_state_dict(self.q_net1.state_dict())
        self.target_q_net2.load_state_dict(self.q_net2.state_dict())

        self.value_optimizer = optim.Adam(self.value_net.parameters(), lr=self.lr)
        # Combine Q-network parameters for a single optimizer
        self.q_optimizer = optim.Adam(list(self.q_net1.parameters()) + list(self.q_net2.parameters()), lr=self.lr)
        self.policy_optimizer = optim.Adam(self.policy_net.parameters(), lr=self.lr)

        if self.auto_entropy_tuning:
            self.log_alpha = torch.tensor(np.log(self.alpha.item()), requires_grad=True, device=self.device)
            self.alpha_optimizer = optim.Adam([self.log_alpha], lr=self.lr)

        self.replay_buffer = ReplayBuffer(args.replay_size)
        self.updates = 0

    def select_action(self, state, evaluate=False):
        state = torch.FloatTensor(state).to(self.device).unsqueeze(0)
        if not evaluate:
            action, _, _, _ = self.policy_net.sample(state)
        else:
            mean, _ = self.policy_net.forward(state)
            action = torch.tanh(mean)
        return action.detach().cpu().numpy()[0]

    def update_parameters(self, memory, batch_size, updates, writer):
        try:
            state_batch, action_batch, reward_batch, next_state_batch, terminated_batch = memory.sample(batch_size)
        except ValueError as e:
            print(f"Warning: {e}")
            return

        state_batch = torch.FloatTensor(state_batch).to(self.device)
        next_state_batch = torch.FloatTensor(next_state_batch).to(self.device)
        action_batch = torch.FloatTensor(action_batch).to(self.device)
        reward_batch = torch.FloatTensor(reward_batch).unsqueeze(1).to(self.device)
        terminated_batch = torch.FloatTensor(terminated_batch).unsqueeze(1).to(self.device)

        with torch.no_grad():
            next_state_action, next_state_log_pi, _, _ = self.policy_net.sample(next_state_batch)
            q1_next_target, q2_next_target = self.target_q_net1(next_state_batch, next_state_action)
            min_q_next_target = torch.min(q1_next_target, q2_next_target) - self.alpha * next_state_log_pi
            next_q_value = reward_batch + (1 - terminated_batch) * self.gamma * min_q_next_target

        q1, q2 = self.q_net1(state_batch, action_batch)
        q1_loss = F.mse_loss(q1, next_q_value)
        q2_loss = F.mse_loss(q2, next_q_value)
        q_loss = q1_loss + q2_loss

        self.q_optimizer.zero_grad()
        q_loss.backward()
        self.q_optimizer.step()

        pi, log_pi, _, _ = self.policy_net.sample(state_batch)
        q1_pi, q2_pi = self.q_net1(state_batch, pi)
        min_q_pi = torch.min(q1_pi, q2_pi)
        policy_loss = ((self.alpha * log_pi) - min_q_pi).mean()

        self.policy_optimizer.zero_grad()
        policy_loss.backward()
        self.policy_optimizer.step()

        alpha_loss = torch.tensor(0.0).to(self.device)
        if self.auto_entropy_tuning:
            alpha_loss = -(self.log_alpha * (log_pi + self.target_entropy).detach()).mean()
            self.alpha_optimizer.zero_grad()
            alpha_loss.backward()
            self.alpha_optimizer.step()
            self.alpha = self.log_alpha.exp()

        # Soft update target networks
        for target_param, param in zip(self.target_q_net1.parameters(), self.q_net1.parameters()):
            target_param.data.copy_(target_param.data * (1.0 - self.tau) + param.data * self.tau)
        for target_param, param in zip(self.target_q_net2.parameters(), self.q_net2.parameters()):
            target_param.data.copy_(target_param.data * (1.0 - self.tau) + param.data * self.tau)

        if writer is not None:
            writer.add_scalar('loss/q_loss', q_loss.item(), updates)
            writer.add_scalar('loss/policy_loss', policy_loss.item(), updates)
            writer.add_scalar('alpha', self.alpha.item(), updates)
            writer.add_scalar('loss/alpha_loss', alpha_loss.item(), updates)

#Evaluate agent
def evaluate_agent(env, agent, num_episodes, seed, writer, hparams):
    print("\n Starting Evaluation")
    all_rewards, all_maes, all_mses, all_r2s, all_csmes = [], [], [], [], []
    for i in range(num_episodes):
        obs, info = env.reset(seed=seed + i)
        episode_reward = 0
        done, truncated = False, False
        sensed_coords = []
        sensed_values = []
        episode_squared_errors = []

        while not done and not truncated:
            action = agent.select_action(obs, evaluate=True)
            action_reshaped = action.reshape(env.unwrapped.num_agents, 2)
            obs, reward, done, truncated, info = env.step(action_reshaped)
            episode_reward += reward

            valid_sensed_data = [item for item in info["sensed_values"] if hasattr(item, '__iter__') and len(item) >= 2]

            temp_coords = []
            temp_values = []
            current_step_squared_errors = []
            for item in valid_sensed_data:
                try:
                    x, y, sensed_value = item
                    temp_coords.append([x, y])
                    temp_values.append(sensed_value)

                    # Calculate squared error for CSME at visited cells
                    x_int, y_int = int(round(x)), int(round(y))
                    x_int = np.clip(x_int, 0, env.unwrapped.map_size[1] - 1)
                    y_int = np.clip(y_int, 0, env.unwrapped.map_size[0] - 1)
                    true_value = env.unwrapped.gt_map_normalized[y_int, x_int]
                    squared_error = (sensed_value - true_value)**2
                    current_step_squared_errors.append(squared_error)

                except IndexError:
                    print(f"Warning: Skipping malformed data point: {item}")
                    continue

            sensed_coords.extend(temp_coords)
            sensed_values.extend(temp_values)
            episode_squared_errors.extend(current_step_squared_errors) # Accumulate squared errors


        all_rewards.append(episode_reward)

        sensed_coords_np = np.array(sensed_coords)

        # Calculate CSME for the episode
        if episode_squared_errors:
             csme = np.mean(episode_squared_errors)
             all_csmes.append(csme)
        else:
             all_csmes.append(np.nan) # Append NaN if no cells were visited

        if len(sensed_coords_np) >= 3:
            gt_map = env.unwrapped.gt_map_normalized
            grid_x, grid_y = np.meshgrid(np.arange(env.unwrapped.map_size[1]), np.arange(env.unwrapped.map_size[0]))
            try:
                estimated_map = LinearNDInterpolator(sensed_coords_np, sensed_values)(grid_x, grid_y)
                estimated_map[np.isnan(estimated_map)] = np.mean(sensed_values) if sensed_values else 0.0
                all_maes.append(mean_absolute_error(gt_map, estimated_map))
                all_mses.append(mean_squared_error(gt_map, estimated_map))
                all_r2s.append(r2_score(gt_map.flatten(), estimated_map.flatten()))
            except ValueError as e:
                print(f"Interpolation failed for this episode: {e}")
                all_maes.append(np.nan)
                all_mses.append(np.nan)
                all_r2s.append(np.nan)
        else:
            print(f"Not enough unique points ({len(sensed_coords_np)}) for interpolation in this episode.")
            all_maes.append(np.nan)
            all_mses.append(np.nan)
            all_r2s.append(np.nan)

    results = {
        "Avg Reward": np.mean(all_rewards),
        "MAE (Full Map)": np.nanmean(all_maes),
        "MSE (Full Map)": np.nanmean(all_mses),
        "R2 (Full Map)": np.nanmean(all_r2s),
        "CSME (Visited Cells)": np.nanmean(all_csmes)
    }
    print("Final Evaluation Results:")
    for key, value in results.items(): print(f"  {key}: {value:.4f}")

    sanitized_hparams = {k: v for k, v in hparams.items() if isinstance(v, (str, int, float, bool))}
    writer.add_hparams(sanitized_hparams, results)

    return results

