class AlgaeBloomGroundTruth:
    @staticmethod
    def generate_map(map_size, map_seed=None):
        if map_seed is not None:
            np.random.seed(map_seed)

        data = np.zeros(map_size)
        num_blooms = np.random.randint(2, 5) # Create 2 to 4 blooms

        for _ in range(num_blooms):
            center_x = np.random.uniform(0.1, 0.9) * map_size[1]
            center_y = np.random.uniform(0.1, 0.9) * map_size[0]
            radius_x = np.random.uniform(0.1, 0.3) * map_size[1]
            radius_y = np.random.uniform(0.1, 0.3) * map_size[0]
            amplitude = np.random.uniform(0.5, 1.0)
            X, Y = np.meshgrid(np.arange(map_size[1]), np.arange(map_size[0]))
            data += amplitude * np.exp(-((X - center_x)**2 / (2 * radius_x**2) + (Y - center_y)**2 / (2 * radius_y**2)))

        # Normalize the final map
        if np.max(data) > np.min(data):
            data = (data - data.min()) / (data.max() - data.min())
        else:
            data = np.zeros(map_size)
        return data

class ShekelGroundTruth:
    @staticmethod
    def generate_map(map_size, map_seed=None):
        if map_seed is not None:
            np.random.seed(map_seed)

        num_peaks = np.random.randint(5, 12)
        peaks_A = np.random.rand(num_peaks) * 10
        peaks_C = np.random.rand(num_peaks, 2)
        peaks_C[:, 0] *= map_size[1]
        peaks_C[:, 1] *= map_size[0]

        X, Y = np.meshgrid(np.arange(map_size[1]), np.arange(map_size[0]))
        data = np.zeros(map_size)

        for i in range(num_peaks):
            # Using Shekel function structure
            denominator = ((X - peaks_C[i, 0])**2 + (Y - peaks_C[i, 1])**2) + peaks_A[i]
            data += 1 / (denominator + 1e-6)

        # Normalize the final map
        if np.max(data) > np.min(data):
            data = (data - data.min()) / (data.max() - data.min())
        else:
            data = np.zeros(map_size)
        return data

class MultiAgentMonitoring(gym.Env):
    def __init__(self, map_size, num_agents, movement_cost_factor, sensor_stds, max_episode_steps,
                 map_class=None, map_seed=None,
                 reward_scale_factor=1.0, collision_threshold=0.05,
                 # Reward weights passed as args
                 collision_penalty=-5.0, reward_visited_cells=1.0,
                 reward_peak_discovery=5.0, penalty_time=0.00001, penalty_revisit=0.0):
        super(MultiAgentMonitoring, self).__init__()

        self.map_size = map_size
        self.num_agents = num_agents
        self.movement_cost_factor = movement_cost_factor
        self.sensor_stds = sensor_stds
        self.max_episode_steps = max_episode_steps
        self.reward_scale_factor = reward_scale_factor
        self.collision_threshold = collision_threshold
        self.collision_penalty = collision_penalty

        self.map_class = map_class
        self.map_seed = map_seed
        self.gt_map = None
        self.gt_map_normalized = None

        self.reward_weights = {
            'visited_cells': reward_visited_cells,
            'peak_discovery': reward_peak_discovery,
            'time_penalty': penalty_time,
            'revisit_penalty': penalty_revisit
        }

        # Observation space to include sensed value
        self.observation_dim = self.num_agents * 3 # (x, y, value) for each agent
        self.observation_space = spaces.Box(low=-np.inf, high=np.inf, shape=(self.observation_dim,), dtype=np.float32)

        # Action space: num_agents * 2 (for x, y delta)
        self.action_space = spaces.Box(low=-1.0, high=1.0, shape=(self.num_agents, 2), dtype=np.float32)

        self.current_step = 0
        self.fleet_positions = None
        self.visited_map = np.zeros(self.map_size)
        self.initial_visited_cells_count = 0
        self.np_random = None

    def _generate_new_map(self):
        if self.map_class:
            # Use a new seed for each map generation to ensure variety
            current_seed = self.np_random.integers(0, 2**32 - 1)
            self.gt_map = self.map_class.generate_map(self.map_size, map_seed=current_seed)
            self.gt_map_normalized = self.gt_map
        else:
            # Fallback to a random map if no class is provided
            self.gt_map = self.np_random.random(self.map_size)
            self.gt_map_normalized = self.gt_map

    def _get_obs(self):
        obs = []
        for i in range(self.num_agents):
            x, y = self.fleet_positions[i]
            # Discretize position to read from the map grid
            x_int, y_int = int(round(x)), int(round(y))
            x_int = np.clip(x_int, 0, self.map_size[1] - 1)
            y_int = np.clip(y_int, 0, self.map_size[0] - 1)
            true_value = self.gt_map_normalized[y_int, x_int]

            noisy_value = true_value + self.np_random.normal(0, self.sensor_stds)
            noisy_value = np.clip(noisy_value, 0.0, 1.0)
            # Normalize positions to [0, 1] range for the observation
            obs.extend([x / (self.map_size[1] - 1), y / (self.map_size[0] - 1), noisy_value])
        return np.array(obs, dtype=np.float32)

    def _sense_and_record(self):
        sensed_values_at_step = []
        for i in range(self.num_agents):
            x, y = self.fleet_positions[i]
            x_int, y_int = int(round(x)), int(round(y))
            x_int = np.clip(x_int, 0, self.map_size[1] - 1)
            y_int = np.clip(y_int, 0, self.map_size[0] - 1)
            true_value = self.gt_map_normalized[y_int, x_int]
            noisy_value = true_value + self.np_random.normal(0, self.sensor_stds)
            noisy_value = np.clip(noisy_value, 0.0, 1.0)
            sensed_values_at_step.append((x, y, noisy_value))
            # Mark cell as visited if it's not an obstacle
            if true_value >= self.collision_threshold:
                self.visited_map[y_int, x_int] = 1
        return sensed_values_at_step

    def _calculate_reward(self, current_sensed_values_info):
        reward = 0.0
        # Reward for visiting NEW cells
        current_visited_cells_count = np.sum(self.visited_map)
        newly_visited_cells = current_visited_cells_count - self.initial_visited_cells_count
        reward += self.reward_weights['visited_cells'] * newly_visited_cells
        self.initial_visited_cells_count = current_visited_cells_count

        # Reward for discovering high-value peaks, based on sensed value
        current_step_sensed_values = [val for _, _, val in current_sensed_values_info]
        if current_step_sensed_values:
            peak_reward = np.max(current_step_sensed_values)
            reward += self.reward_weights['peak_discovery'] * peak_reward

        # Penalty for time
        reward -= self.reward_weights['time_penalty']
        return reward

    def reset(self, seed=None, options=None):
        super().reset(seed=seed)
        if seed is not None:
            self.np_random, _ = gym.utils.seeding.np_random(seed)
        else:
            self.np_random, _ = gym.utils.seeding.np_random()

        self._generate_new_map()

        self.fleet_positions = np.zeros((self.num_agents, 2), dtype=np.float32)
        # Initialize agents in valid non-obstacle positions
        for i in range(self.num_agents):
            valid_pos_found = False
            attempts = 0
            while not valid_pos_found and attempts < 1000:
                x = self.np_random.uniform(0, self.map_size[1])
                y = self.np_random.uniform(0, self.map_size[0])
                x_int, y_int = int(round(x)), int(round(y))
                if 0 <= y_int < self.map_size[0] and 0 <= x_int < self.map_size[1]:
                    if self.gt_map_normalized[y_int, x_int] >= self.collision_threshold:
                        self.fleet_positions[i, 0] = x
                        self.fleet_positions[i, 1] = y
                        valid_pos_found = True
                attempts += 1
            if not valid_pos_found:
                print(f"Warning: Could not find a valid start pos for agent {i}. Placing at (0,0).")
                self.fleet_positions[i, 0] = 0
                self.fleet_positions[i, 1] = 0

        self.current_step = 0
        self.visited_map = np.zeros(self.map_size)
        self.initial_visited_cells_count = 0
        initial_sensed_values = self._sense_and_record()
        self.initial_visited_cells_count = np.sum(self.visited_map)

        obs = self._get_obs()
        info = {"fleet_positions": self.fleet_positions.copy(), "sensed_values": initial_sensed_values}
        return obs, info

    def step(self, action):
        action = np.array(action).reshape(self.num_agents, 2)
        old_positions = self.fleet_positions.copy()
        collision_reward_penalty = 0.0

        intended_new_positions = self.fleet_positions + action
        new_fleet_positions = old_positions.copy()

        for i in range(self.num_agents):
            int_x = int(round(intended_new_positions[i, 0]))
            int_y = int(round(intended_new_positions[i, 1]))

            if 0 <= int_x < self.map_size[1] and 0 <= int_y < self.map_size[0]:
                if self.gt_map_normalized[int_y, int_x] < self.collision_threshold:
                    collision_reward_penalty += self.collision_penalty
                else:
                    new_fleet_positions[i] = intended_new_positions[i]
            else:
                new_fleet_positions[i, 0] = np.clip(intended_new_positions[i, 0], 0, self.map_size[1] - 1)
                new_fleet_positions[i, 1] = np.clip(intended_new_positions[i, 1], 0, self.map_size[0] - 1)
                collision_reward_penalty += self.collision_penalty

        self.fleet_positions = new_fleet_positions
        movement_cost = np.sum(np.abs(action)) * self.movement_cost_factor

        current_sensed_values_info = self._sense_and_record()
        reward_from_env = self._calculate_reward(current_sensed_values_info)

        # Combine all reward components and apply scale factor
        reward = (reward_from_env - movement_cost + collision_reward_penalty) * self.reward_scale_factor

        self.current_step += 1
        terminated = False
        truncated = self.current_step >= self.max_episode_steps

        obs = self._get_obs()
        info = {"fleet_positions": self.fleet_positions.copy(), "sensed_values": current_sensed_values_info}
        return obs, reward, terminated, truncated, info

    def render(self):
        plt.figure(figsize=(10, 8))
        if self.gt_map_normalized is not None:
            plt.imshow(self.gt_map_normalized, origin='lower', cmap='viridis', alpha=0.7)
            obstacle_mask = self.gt_map_normalized < self.collision_threshold
            plt.imshow(obstacle_mask, origin='lower', cmap='binary', alpha=0.5)
        plt.imshow(self.visited_map, origin='lower', cmap='bone_r', alpha=0.3)
        if self.fleet_positions is not None:
            plt.scatter(self.fleet_positions[:, 0], self.fleet_positions[:, 1], c='red', marker='o', s=100, label='Agents', edgecolors='black')
        plt.title(f"Map Monitoring - Step: {self.current_step}")
        plt.xlabel("X Coordinate")
        plt.ylabel("Y Coordinate")
        plt.colorbar(label="Normalized Value")
        plt.legend()
        plt.grid(True)
        plt.show()

    def close(self):
        plt.close()

